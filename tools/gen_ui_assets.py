CELL, GLYPH = 16, 14
SHADES = {"#": 255, "=": 150}


def parse(art: str) -> list[str]:
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == GLYPH, f"{len(rows)} lignes au lieu de {GLYPH}"
    for r in rows:
        assert len(r) == GLYPH, f"ligne de {len(r)} caractères : {r!r}"
    return rows


def add_outline(img: Image.Image, color) -> None:
    """Contour 1 px (4 voisins) autour des pixels opaques."""
    w, h = img.size
    src = img.load()
    solid = {(x, y) for y in range(h) for x in range(w) if src[x, y][3] > 0}
    for x, y in [(x + dx, y + dy) for x, y in solid for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]:
        if 0 <= x < w and 0 <= y < h and (x, y) not in solid:
            src[x, y] = color


def build_icons(out: Path) -> None:
    atlas = Image.new("RGBA", (CELL * len(ICONS), CELL), (0, 0, 0, 0))
    for i, (name, art) in enumerate(ICONS.items()):
        cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
        px = cell.load()
        for y, row in enumerate(parse(art)):
            for x, c in enumerate(row):
                if c in SHADES:
                    v = SHADES[c]
                    px[x + 1, y + 1] = (v, v, v, 255)
        add_outline(cell, (0, 0, 0, 200))
        atlas.paste(cell, (i * CELL, 0))
    atlas.save(out)
    print(f"{out} : {len(ICONS)} icônes")


# ─── Logo ────────────────────────────────────────────────────────────────────
# Lettres 9x12, trait de 3 px, coins coupés en haut à gauche et en bas à droite.

LETTERS = {
    "A": ["..#######", ".########"] + ["###...###"] * 3 + ["#########"] * 2 + ["###...###"] * 5,
    "U": ["###...###"] * 10 + ["########.", "#######.."],
    "G": ["..#######", ".########", "###......", "###......", "###......", "###..####", "###..####",
          "###...###", "###...###", "###...###", "########.", "#######.."],
    "T": ["#########", "#########"] + ["...###..."] * 10,
    "O": ["..#######", ".########"] + ["###...###"] * 8 + ["########.", "#######.."],
    "N": ["#######..", "########."] + ["###...###"] * 10,
}


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def build_logo(out: Path, word: str = "AUGATON") -> None:
    LW, LH, GAP, DEPTH = 9, 12, 2, 3
    width = len(word) * LW + (len(word) - 1) * GAP
    mask = [[False] * width for _ in range(LH)]
    for i, ch in enumerate(word):
        for y, row in enumerate(LETTERS[ch]):
            for x, c in enumerate(row):
                if c == "#":
                    mask[y][i * (LW + GAP) + x] = True

    pad = 1
    W, H = width + 2 * pad + DEPTH, LH + 2 * pad + DEPTH
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    px = img.load()

    # Extrusion (profondeur) en diagonale, du plus sombre au plus proche
    for d in range(DEPTH, 0, -1):
        col = lerp((40, 10, 48), (120, 30, 90), (DEPTH - d) / max(1, DEPTH - 1))
        for y in range(LH):
            for x in range(width):
                if mask[y][x]:
                    px[x + pad + d, y + pad + d] = col + (255,)

    # Face : dégradé « chrome couchant », ligne d'horizon au milieu
    top = [(255, 252, 235), (255, 214, 120)]
    bottom = [(255, 150, 40), (226, 58, 46)]
    for y in range(LH):
        if y < LH // 2:
            col = lerp(*top, y / (LH // 2 - 1))
        else:
            col = lerp(*bottom, (y - LH // 2) / (LH - LH // 2 - 1))
        for x in range(width):
            if mask[y][x]:
                c = col
                if y == LH // 2:                       # horizon : trait sombre
                    c = lerp(col, (120, 30, 60), 0.55)
                elif y == 0 or not mask[y - 1][x]:     # arête supérieure éclairée
                    c = lerp(col, (255, 255, 255), 0.6)
                px[x + pad, y + pad] = c + (255,)

    add_outline(img, (16, 6, 20, 255))
    img.save(out)
    print(f"{out} : {W}x{H}")


